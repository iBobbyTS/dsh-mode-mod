/**
 * Tool and prompt boundary for the 资料搜索 (web research) agent preset.
 *
 * The preset mounts this row so its sessions see the Playwright browser tools
 * and nothing else. The restriction is registered in the PRESET scope, which
 * every agent of that preset inherits: inherited tools (bash, fs and other
 * MCP servers) are masked. The host preserves an Agent's own registrations,
 * so a thin NativeToolExecutor description filter enforces the final model
 * allow list, and a scoped monotonic guard denies non-browser execution.
 * Native execution retains all scheduling, approval and cancellation behavior.
 *
 * Three upstream tools are deliberately not in the allow list:
 * browser_run_code_unsafe (arbitrary JavaScript in the MCP server process,
 * i.e. local code execution), and browser_file_upload / browser_drop (push
 * local files into a page). Keeping them out is what makes "browser only" a
 * real boundary rather than a prompt-level promise.
 *
 * The same boundary covers prompt text the mode cannot use. The shared MCP
 * resource section and every connected MCP server's instruction section are
 * shadowed in the preset scope: the mode masks the resource tools, and it has
 * no codegraph/external_subagent tools, so their descriptions would only
 * describe capabilities this session does not have. The browser server's own
 * instructions stay visible. The preset persona also suppresses optional
 * runtime context, and this row shadows the required working-directory
 * context, so a research turn carries no runtime-context injection: the
 * sandbox policy, approval policy, checkout, GUI URL, and working directory
 * all describe machinery a browser-only session cannot use.
 *
 * Load order is not guaranteed: the profile's Playwright MCP row starts after
 * this bundle patch. The mask therefore recomputes on every tools/change and
 * is lifted/reinstalled atomically; until the browser tools exist it denies
 * every global tool instead of waiting with an open catalog, so a session can
 * never fall back to unrelated capabilities.
 * @module @local/dsh-mode-mod/web-research
 */

import type { Context } from '@deepseek-ai/cordis'
import { NativeToolExecutor } from '@deepseek-ai/dsh-tool-executor-native'
import type { ToolDefinition, ToolExecutor, ToolGuard, ToolModelInput } from '@deepseek-ai/dsh-tools'

/** Cordis plugin name; distinct from the preset row id that mounts it. */
export const name = 'mode-mod-web-research'

/** The host tool and prompt registries this row masks for the preset scope. */
export const inject = ['tools', 'systemPrompt']

/** Playwright MCP tool-name prefix generated by the host MCP client. */
const BROWSER_TOOL_PREFIX = 'mcp__playwright__'

/** Server namespace whose tools this mode keeps; every other server is masked. */
const BROWSER_SERVER = 'playwright'

/** Every MCP tool name starts with this, followed by the server namespace. */
const MCP_TOOL_PREFIX = 'mcp__'

/** The MCP client names one server's instruction section `mcp:<server>`. */
const MCP_SECTION_PREFIX = 'mcp:'

/** The shared section that tells the model how to read MCP resources. */
const RESOURCE_SECTION = 'mcp-resource-servers'

/**
 * Prompt sections that describe deployment machinery this browser-only mode
 * cannot use: desktop file/present guidance (the mode has no present tool and
 * no local files) and the harness checkout / Web GUI developer orientation
 * (the mode never inspects or extends DSH). Their contexts are already
 * suppressed; these are the section halves of the same guidance.
 */
const STATIC_SECTION_SHADOWS: readonly { name: string; order: 'HARNESS_IDENTITY' | 'DELIVERABLE_FILE_REFERENCES' | 'HARNESS_SOURCE' | 'WEB_SURFACE' }[] = [
  // The persona is the mode's complete identity; the generic harness opener
  // would only repeat it.
  { name: 'harness:identity', order: 'HARNESS_IDENTITY' },
  { name: 'ui:deliverable-file-references', order: 'DELIVERABLE_FILE_REFERENCES' },
  { name: 'harness:source', order: 'HARNESS_SOURCE' },
  { name: 'app:web-surface', order: 'WEB_SURFACE' },
]

/**
 * The host's required working-directory runtime context. The persona
 * suppresses optional context; shadowing this required name with an empty
 * optional entry leaves the assembly with no runtime-context snapshot.
 */
const WORKING_DIRECTORY_CONTEXT = 'working-directory:current'

/**
 * The browser tools this mode may use, without the server prefix. The allow
 * list is exact: a tool name Playwright adds later stays hidden until it is
 * reviewed and listed here, so an upstream upgrade cannot silently widen the
 * mode's capability.
 */
const BROWSER_TOOL_NAMES = [
  'browser_click',
  'browser_close',
  'browser_console_messages',
  'browser_drag',
  'browser_emulate_media',
  'browser_evaluate',
  'browser_fill_form',
  'browser_find',
  'browser_handle_dialog',
  'browser_hover',
  'browser_navigate',
  'browser_navigate_back',
  'browser_network_request',
  'browser_network_requests',
  'browser_press_key',
  'browser_resize',
  'browser_select_option',
  'browser_snapshot',
  'browser_tabs',
  'browser_take_screenshot',
  'browser_type',
  'browser_wait_for',
]

/** Fully qualified allow list (22 browser tools). */
export const BROWSER_TOOLS: readonly string[] = BROWSER_TOOL_NAMES.map((tool) => BROWSER_TOOL_PREFIX + tool)

/**
 * Upstream tools excluded from the allow list even though they share the
 * browser prefix. Exported so the boundary is testable and documented in one
 * place.
 */
export const EXCLUDED_TOOLS: readonly string[] = [
  'browser_run_code_unsafe',
  'browser_file_upload',
  'browser_drop',
].map((tool) => BROWSER_TOOL_PREFIX + tool)

/** One model-facing tool definition, as much as the mask needs. */
interface ToolSummary { name: string }

/** The host tool-registry filter shape. */
interface ToolFilter { allow?: string[]; deny?: string[] }

/** The subset of the host tool registry used here. */
interface ToolRegistry {
  setExecutor(executor: ToolExecutor): () => void
  guard(guard: ToolGuard): () => void
  /** Model-facing global tool schemas (the deployment view, not an agent view). */
  schemas(): readonly ToolSummary[]
  /** Mask inherited tools for the calling scope; returns the exact lifter. */
  restrict(filter: ToolFilter): () => void
}

/** One prompt section this row registers in the preset scope. */
interface PromptSection { name: string; order: number; text: string }

/** One runtime-context entry this row registers in the preset scope. */
interface PromptContext { name: string; order: number; text: string }

/** The subset of the host prompt registry used here. */
interface PromptRegistry {
  section(section: PromptSection): () => void
  context(context: PromptContext): () => void
  getSectionOrder(name: string): number
  getContextOrder(name: string): number
}

/** The subset of the plugin context used here. */
interface WebResearchContext {
  logger: { warn(message: string): void; info(message: string): void }
  tools: ToolRegistry
  systemPrompt: PromptRegistry
  on(name: 'tools/change', listener: () => void): () => void
  effect(execute: () => () => void, label: string): unknown
}

/**
 * Read the MCP server namespace out of one tool name.
 * @param tool - model-facing tool name.
 * @returns the server name, or undefined for a non-MCP tool.
 */
function mcpServerOf(tool: string): string | undefined {
  if (!tool.startsWith(MCP_TOOL_PREFIX)) return undefined
  const rest = tool.slice(MCP_TOOL_PREFIX.length)
  const end = rest.indexOf('__')
  return end > 0 ? rest.slice(0, end) : undefined
}

/**
 * Choose the tool filter the preset scope should carry.
 * @param globals - current global tool names.
 * @returns the allow list for the browser subset, a deny-all fallback before
 *   any browser tool exists, or undefined when the registry is still empty.
 */
function wantedMask(globals: readonly string[]): ToolFilter | undefined {
  const present = BROWSER_TOOLS.filter((tool) => globals.includes(tool))
  if (present.length > 0) return { allow: present }
  // No browser tools yet: hide every other global capability. A session that
  // starts in this window must not inherit bash, fs, run_code, or another MCP
  // server just because the browser has not finished starting.
  const others = globals.filter((tool) => tool !== 'run_code')
  return others.length > 0 ? { deny: others } : undefined
}

/** Stable identity of one filter, used to avoid reinstalling identical masks. */
function filterKey(filter: ToolFilter): string {
  return filter.allow !== undefined ? 'allow:' + filter.allow.join('\u0000') : 'deny:' + (filter.deny ?? []).join('\u0000')
}

/**
 * Registry restrictions deliberately preserve an Agent's own registrations.
 * The preset's native executor therefore owns the final declaration boundary;
 * NativeToolExecutor retains execution, approvals, cancellation and settlement.
 */
class BrowserResearchExecutor extends NativeToolExecutor {
  override describe(tools: readonly ToolDefinition[]): ToolModelInput {
    const allowed = tools.filter(tool => BROWSER_TOOLS.includes(tool.name))
    return { ...super.describe(allowed), knownNames: allowed.map(tool => tool.name) }
  }
}

/**
 * Install the preset-scope mask and prompt-section shadows, and keep them in
 * step with the live registry.
 * @param ctx - the preset-scope context that mounts this row.
 */
export function apply(ctx: WebResearchContext): void {
  // Inherited monotonic guards also cover Agent-owned and late registrations,
  // including stale/raw calls absent from the model's declaration list.
  const releaseGuard = ctx.tools.guard(execution => BROWSER_TOOLS.includes(execution.name)
    ? undefined : 'This research preset only permits its browser tool allow list.')
  const releaseExecutor = ctx.tools.setExecutor(new BrowserResearchExecutor(ctx as unknown as Context))
  const mcpSectionOrder = ctx.systemPrompt.getSectionOrder('MCP_SERVERS')
  // The persona suppresses optional context; this empty optional entry shadows
  // the required working-directory context the suppression would keep.
  const directoryShadow = ctx.systemPrompt.context({
    name: WORKING_DIRECTORY_CONTEXT,
    order: ctx.systemPrompt.getContextOrder('WORKING_DIRECTORY'),
    text: '',
  })
  const staticShadows = STATIC_SECTION_SHADOWS.map(({ name, order }) =>
    ctx.systemPrompt.section({ name, order: ctx.systemPrompt.getSectionOrder(order), text: '' }))
  /** Prompt-section shadows owned by this row, by section name. */
  const shadows = new Map<string, () => void>()
  let installedKey = ''
  let lift: (() => void) | undefined
  let disposed = false
  // Restricting emits tools/change; without this guard the listener would
  // re-enter while the mask it just replaced is being lifted.
  let syncing = false

  /**
   * Shadow the MCP prompt text this mode cannot use: the shared resource
   * section and every non-browser server's instruction section.
   * @param globals - current global tool names, which name the connected servers.
   */
  const syncPrompt = (globals: readonly string[]): void => {
    const wanted = new Set<string>([RESOURCE_SECTION])
    for (const tool of globals) {
      const server = mcpServerOf(tool)
      if (server !== undefined && server !== BROWSER_SERVER) wanted.add(MCP_SECTION_PREFIX + server)
    }
    for (const [section, dispose] of shadows) {
      if (wanted.has(section)) continue
      dispose()
      shadows.delete(section)
    }
    for (const section of wanted) {
      if (shadows.has(section)) continue
      shadows.set(section, ctx.systemPrompt.section({ name: section, order: mcpSectionOrder, text: '' }))
    }
  }

  const sync = (): void => {
    if (disposed || syncing) return
    const globals = ctx.tools.schemas().map((tool) => tool.name)
    syncPrompt(globals)
    const next = wantedMask(globals)
    if (next === undefined) return
    const key = filterKey(next)
    if (key === installedKey) return
    syncing = true
    try {
      // Install the replacement before lifting the old mask: restrictions
      // intersect, so the overlap can never expose an unmasked window.
      const nextLift = ctx.tools.restrict(next)
      const previousLift = lift
      lift = nextLift
      installedKey = key
      previousLift?.()
    } catch (error) {
      ctx.logger.warn('mode-mod: web-research tool mask failed: ' + (error instanceof Error ? error.message : String(error)))
    } finally {
      syncing = false
    }
  }

  sync()
  const offChange = ctx.on('tools/change', sync)
  ctx.effect(() => () => {
    disposed = true
    offChange?.()
    releaseExecutor()
    releaseGuard()
    lift?.()
    lift = undefined
    installedKey = ''
    directoryShadow()
    for (const dispose of staticShadows) dispose()
    for (const dispose of shadows.values()) dispose()
    shadows.clear()
  }, 'mode-mod: web-research tool mask')
}
